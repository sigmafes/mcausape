"""Makes the pictures for the animated fire and the eight monster spawners.

  fire    Fire_0_29_JE2_BE2.webp is a strip of 32 frames, 160x160 each. They are shrunk
          to the 16x16 of the terrain atlas and written as a C header the fire's dynamic
          texture plays (src/client/renderer/ptexture/FireFrames.h).
  spawner the cage texture of the monster spawner, tinted once per kind and put in free
          cells of terrain.png: kind 0 stays in cell (8,5), kinds 1..7 go to row 11,
          columns 4..10.
  ghast   ghast_shooting.png from the same pack is the face it pulls while charging.

Run with Pillow:  python -I make_fire_and_spawner_assets.py <fire.webp> <ghast_shooting.png>
"""
import sys
from PIL import Image

HERE = __file__.replace('\\', '/').rsplit('/', 2)[0]          # .../handheld
webp, ghast_shooting = sys.argv[1], sys.argv[2]

# --- fire ------------------------------------------------------------------------------
strip = Image.open(webp).convert('RGBA')
size = strip.width
frames = strip.height // size
rows = []
for i in range(frames):
    f = strip.crop((0, i * size, size, (i + 1) * size))
    # shrink with the colour weighted by alpha, or the edges come out dark
    f = f.convert('RGBa').resize((16, 16), Image.BOX).convert('RGBA')
    rows.append(list(f.tobytes()))

with open(HERE + '/src/client/renderer/ptexture/FireFrames.h', 'w') as out:
    out.write('// Generated by tools/make_fire_and_spawner_assets.py from Fire_0_29_JE2_BE2.webp.\n')
    out.write('// %d frames of the fire, 16x16 RGBA each.\n' % frames)
    out.write('#ifndef NET_MINECRAFT_CLIENT_RENDERER_PTEXTURE__FireFrames_H__\n')
    out.write('#define NET_MINECRAFT_CLIENT_RENDERER_PTEXTURE__FireFrames_H__\n\n')
    out.write('static const int FIRE_FRAME_COUNT = %d;\n' % frames)
    out.write('static const unsigned char FIRE_FRAMES[%d][16 * 16 * 4] = {\n' % frames)
    for r in rows:
        out.write('\t{' + ','.join(str(v) for v in r) + '},\n')
    out.write('};\n\n#endif\n')
print('fire: %d frames' % frames)

# --- spawners ----------------------------------------------------------------------------
TINTS = [
    (0.45, 0.95, 0.45),   # 0 zombie        green
    (0.95, 0.95, 0.95),   # 1 skeleton      bone
    (0.80, 0.25, 0.25),   # 2 spider        dark red
    (1.00, 0.60, 0.70),   # 3 pig zombie    pink
    (0.30, 0.30, 0.38),   # 4 wither skel.  charcoal
    (1.00, 0.80, 0.15),   # 5 blaze         yellow
    (1.00, 0.35, 0.10),   # 6 magma cube    orange-red
    (0.75, 0.85, 1.00),   # 7 ghast         pale blue
]
terrain_path = HERE + '/data/images/terrain.png'
terrain = Image.open(terrain_path).convert('RGBA')
base = terrain.crop((8 * 16, 5 * 16, 9 * 16, 6 * 16))     # the cage, as copied from LCE


def cell_for(kind):
    return (8, 5) if kind == 0 else (3 + kind, 11)


for kind, (tr, tg, tb) in enumerate(TINTS):
    cell = Image.new('RGBA', (16, 16))
    px = base.load()
    out_px = cell.load()
    for y in range(16):
        for x in range(16):
            r, g, b, a = px[x, y]
            lum = (r + g + b) / 3.0
            out_px[x, y] = (min(255, int(lum * tr * 1.8)), min(255, int(lum * tg * 1.8)),
                            min(255, int(lum * tb * 1.8)), a)
    cx, cy = cell_for(kind)
    terrain.paste(cell, (cx * 16, cy * 16))
terrain.save(terrain_path)
print('spawner: 8 tinted cells written')

# --- ghast -------------------------------------------------------------------------------
Image.open(ghast_shooting).convert('RGBA').save(HERE + '/data/images/mob/ghast_fire.png')
print('ghast_fire.png written')
